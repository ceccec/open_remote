# frozen_string_literal: true

##
# Comprehensive documentation generator.
# Generates all documentation including README from model features, interactions, and tests.
class ComprehensiveDocsGenerator
  def initialize
    Rails.application.eager_load! if defined?(Rails)
  end

  def generate_all
    puts "📚 Generating comprehensive documentation..."
    puts "=" * 80

    generate_readme
    generate_model_features_doc
    generate_interactions_doc
    generate_capabilities_doc
    generate_architecture_doc
    generate_api_index
    generate_testing_ux_doc
    generate_vitepress_config

    puts "\n✅ All documentation generated successfully!"
  end

  def generate_testing_ux_doc
    puts "\n📝 Generating Testing UX documentation..."

    # Delegate to DocsGenerator for consistency
    begin
      docs_generator_path = Rails.root.join("lib", "tasks", "docs_generator.rb")
      if File.exist?(docs_generator_path)
        require docs_generator_path.to_s
        generator = DocsGenerator.new
        generator.send(:generate_testing_ux_doc)
        puts "  ✅ docs/testing-ux.md"
      else
        puts "  ⚠️  DocsGenerator not found, skipping Testing UX doc"
      end
    rescue LoadError, StandardError => e
      puts "  ⚠️  Testing UX doc generation failed: #{e.message}"
    end
  end

  def generate_vitepress_config
    puts "\n⚙️  Generating VitePress config..."

    # Use the existing DocsGenerator to generate VitePress config
    # This requires discovering components first
    begin
      docs_generator_path = Rails.root.join("lib", "tasks", "docs_generator.rb")
      if File.exist?(docs_generator_path)
        require docs_generator_path.to_s
        generator = DocsGenerator.new
        # Discover components and examples needed for config generation
        generator.send(:discover_components)
        generator.send(:extract_test_examples)
        generator.generate_vitepress_config

        # Verify auto-generated header was added
        config_path = Rails.root.join("docs", ".vitepress", "config.js")
        if File.exist?(config_path)
          content = File.read(config_path)
          unless content.include?("Auto-generated")
            # Add header if missing (shouldn't happen, but safety check)
            content = "// Auto-generated VitePress configuration\n" \
                     "// To regenerate: rake docs:generate_all or rake docs:from_tests\n" \
                     "// Last updated: #{Time.current.strftime("%Y-%m-%d %H:%M:%S")}\n" \
                     "//\n" \
                     "// This file is automatically generated from Rails components.\n" \
                     "// Do not edit manually - changes will be overwritten.\n\n" + content
            File.write(config_path, content)
          end
        end

        puts "  ✅ docs/.vitepress/config.js (auto-generated)"
      else
        puts "  ⚠️  DocsGenerator not found, skipping VitePress config"
      end
    rescue LoadError, StandardError => e
      puts "  ⚠️  VitePress config generation failed: #{e.message}"
      puts "     Run 'rake docs:from_tests' to generate VitePress config"
    end
  end

