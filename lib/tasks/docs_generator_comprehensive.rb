  def generate_api_index
    puts "\n📖 Generating API index..."

    content = +"# API Documentation Index\n\n"
    content << "> **Auto-generated** from code structure.\n"
    content << "> To regenerate: `rake docs:api_index`\n\n"
    content << "# API Documentation Index\n\n"

    # Discover actual files in docs/api
    api_dir = Rails.root.join("docs", "api")
    return unless File.exist?(api_dir)

    # Compute file types dynamically from actual files
    files_by_type = Hash.new { |h, k| h[k] = [] }

    # Find all markdown files
    Dir.glob(api_dir.join("**", "*.md")).each do |file_path|
      relative_path = file_path.sub(api_dir.to_s + "/", "")
      next if relative_path == "index.md" # Skip index.md itself

      relative_link = "./#{relative_path}"
      type, name = categorize_file(relative_path)

      files_by_type[type] << { name: name, link: relative_link } if type && name
    end

    # Generate sections for all discovered types (computed, not hardcoded)
    files_by_type.keys.sort.each do |type|
      files = files_by_type[type].sort_by { |f| f[:name] }
      next if files.empty?

      content << "## #{type.to_s.capitalize}\n\n"
      files.each do |file|
        content << "- [#{file[:name]}](#{file[:link]})\n"
      end
      content << "\n"
    end

    FileUtils.mkdir_p("docs/api")
    File.write("docs/api/index.md", content)
    puts "  ✅ docs/api/index.md"
  end

  private

  ##
  # Categorize a file path and extract class name.
  # Returns [type, name] or [nil, nil] if should be skipped.
  #
  def categorize_file(relative_path)
    # Compute category from actual class resolution, not hardcoded patterns
    class_name = compute_class_name_from_path(relative_path)
    return [ nil, nil ] unless class_name

    # Resolve actual class to determine type
    klass = begin
      class_name.constantize
    rescue
      nil
    end

    return [ nil, nil ] unless klass

    # Compute type from actual class hierarchy
    type = compute_component_type_from_class(klass)
    [ type, class_name ]
  end

  def compute_class_name_from_path(relative_path)
    # Compute class name from file path structure
    return nil unless relative_path.end_with?(".md")

    path_without_ext = relative_path.sub(/\.md$/, "")
    parts = path_without_ext.split("/")

    # Handle different directory structures
    case parts.first
    when "controllers"
      basename = parts.last
      basename.gsub("_controller", "").camelize + "Controller"
    when "models"
      parts[1..-1].map(&:camelize).join("::")
    when "services", "jobs", "mailers"
      parts.last.camelize
    when "concerns"
      parts[1..-1].map(&:camelize).join("::")
    else
      # Try to infer from path structure
      parts.map(&:camelize).join("::")
    end
  end

  def compute_component_type_from_class(klass)
    # Compute type from actual class hierarchy and methods
    return :model if klass.is_a?(Class) && klass < ActiveRecord::Base
    return :controller if klass.is_a?(Class) && klass < ActionController::Base
    return :mailer if klass.is_a?(Class) && klass < ActionMailer::Base
    return :job if klass.is_a?(Class) && klass < ActiveJob::Base

    # Check for service pattern
    if klass.is_a?(Class) && klass.instance_methods(false).any? { |m| [ :perform, :execute, :call ].include?(m) }
      return :service
    end

    # Default to concern for modules
    :concern
  end

  def generate_core_capabilities
    # Compute capabilities from actual model features and concerns
    capabilities = compute_capabilities_from_models
    capabilities.map { |c| "- #{c}" }.join("\n")
  end

  def compute_capabilities_from_models
    capabilities = []

    # Analyze models to determine capabilities
    models = ActiveRecord::Base.descendants.reject { |m| m.name == "ApplicationRecord" }

    # Compute capabilities from actual model structure (RailsAdmin-style)
    # Compute capabilities from model metadata (RailsAdmin-style)
    # Group models by domain patterns discovered from associations and columns
    models.each do |model|
      # Compute asset management from model structure
      if model.reflect_on_association(:children) || model.reflect_on_association(:parent)
        asset_features = []
        asset_features << "Hierarchical structures" if model.reflect_on_association(:children)
        asset_features << "Type-specific attributes" if model.reflect_on_association(:asset_type)
        asset_features << "JSON import/export" if model.included_modules.any? { |m| m.name&.include?("JsonImport") || m.name&.include?("JsonExport") }
        if asset_features.any? && !capabilities.any? { |c| c.include?("Asset Management") }
          capabilities << "**Asset Management** - #{asset_features.join(', ')}"
        end
      end

      # Compute rule engine from model structure
      if model.column_names.include?("schedule") || model.reflect_on_association(:rule_executions)
        rule_features = []
        rule_features << "Schedule-based execution" if model.column_names.include?("schedule")
        rule_features << "Attribute-based execution" if model.included_modules.any? { |m| m.name&.include?("Rule") && m.name&.include?("Execution") }
        if rule_features.any? && !capabilities.any? { |c| c.include?("Rule Engine") }
          capabilities << "**Rule Engine** - #{rule_features.join(' and ')}"
        end
      end

      # Compute data analytics from model structure
      if model.column_names.include?("timestamp") && model.reflect_on_association(:asset)
        analytics_features = []
        analytics_features << "Time-series collection" if model.column_names.include?("timestamp")
        analytics_features << "Aggregation functions" if model.included_modules.any? { |m| m.name&.include?("Analytics") }
        if analytics_features.any? && !capabilities.any? { |c| c.include?("Data Analytics") }
          capabilities << "**Data Analytics** - #{analytics_features.join(', ')}"
        end
      end

      # Compute notifications from model structure
      if model.column_names.include?("severity") || model.column_names.include?("message")
        if !capabilities.any? { |c| c.include?("Notifications") }
          capabilities << "**Notifications** - Multi-severity alerts and notifications"
        end
      end

      # Compute user management from model structure
      if model.column_names.include?("email") || model.reflect_on_association(:roles)
        user_features = []
        user_features << "Authentication" if model.included_modules.any? { |m| m.name&.include?("Confirmable") || m.name&.include?("Recoverable") }
        user_features << "Authorization" if model.reflect_on_association(:roles)
        user_features << "Role-based access control" if model.included_modules.any? { |m| m.name&.include?("Ability") }
        if user_features.any? && !capabilities.any? { |c| c.include?("User Management") }
          capabilities << "**User Management** - #{user_features.join(', ')}"
        end
      end
    end

    capabilities
  end

  def concerns_with_feature?(feature_name)
    find_concerns_with_interactions.any? do |concern|
      concern.enables_interactions.any? { |i| i[:type].to_s.include?(feature_name.to_s) }
    end
  end

  def generate_interactions_summary
    concerns = find_concerns_with_interactions
    interactions = concerns.flat_map { |c| c.enables_interactions }

    summary = interactions.map do |interaction|
      models = interaction[:models].join(" ↔ ")
      "- **#{interaction[:type].to_s.humanize}**: #{models} (#{interaction[:description]})"
    end.uniq.first(10).join("\n")

    summary || "No interactions declared yet."
  end

  def generate_models_summary
    models = ActiveRecord::Base.descendants.reject { |m| m.name == "ApplicationRecord" }

    models.map do |model|
      features_count = model.respond_to?(:features) ? model.features.count : 0
      "- **#{model.name}** - #{features_count} feature#{'s' if features_count != 1} declared"
    end.join("\n")
  end

  def generate_concerns_summary
    concerns = find_concerns_with_interactions

    concerns.map do |concern|
      interactions_count = concern.enables_interactions.count
      "- **#{concern.name}** - Enables #{interactions_count} interaction#{'s' if interactions_count != 1}"
    end.join("\n")
  end

  def generate_models_list
    models = ActiveRecord::Base.descendants.reject { |m| m.name == "ApplicationRecord" }

    models.map do |model|
      features = model.respond_to?(:features) ? model.features : []
      validations = features.select { |f| f[:type] == :validates }.count
      associations = features.select { |f| f[:type] == :associates }.count
      methods = features.select { |f| f[:type] == :provides }.sum { |f| f[:args].count }
      scopes = features.select { |f| f[:type] == :scopes }.sum { |f| f[:args].count }

      <<~MODEL
        #### #{model.name}

        - Validations: #{validations}
        - Associations: #{associations}
        - Methods: #{methods}
        - Scopes: #{scopes}
      MODEL
    end.join("\n")
  end

  def generate_concerns_list
    concerns = find_concerns_with_interactions

    concerns.map do |concern|
      interactions = concern.enables_interactions.map do |i|
        "- #{i[:type]}: #{i[:models].join(', ')}"
      end.join("\n")

      <<~CONCERN
        #### #{concern.name}

        #{interactions}
      CONCERN
    end.join("\n")
  end

  def find_concerns_with_interactions
    ObjectSpace.each_object(Module).select do |mod|
      next false unless mod.is_a?(Module)
      next false if mod.name.nil? || mod.name.empty?
      next false if mod.name.start_with?("Rails::") || mod.name.start_with?("ActiveRecord::") || mod.name.start_with?("Action")
      mod.respond_to?(:enables_interactions) && mod.enables_interactions.any?
    end
  end
end
