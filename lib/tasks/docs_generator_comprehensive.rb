  def generate_model_features_doc
    puts "\n📋 Generating model features documentation..."

    content = +"# Model Features\n\n"
    content << "> **Auto-generated** from model feature declarations.\n"
    content << "> To regenerate: `rake docs:features`\n\n"
    content << "This document describes features declared by each model.\n\n"
    content << "**Last Updated**: #{Time.current.strftime("%Y-%m-%d %H:%M:%S")}\n\n"
    content << "---\n\n"

    models = ActiveRecord::Base.descendants.select { |m| m.respond_to?(:features) && m.features.any? }

    models.each do |model|
      content << model.feature_documentation
      content << "\n---\n\n"
    end

    File.write("docs/model_features.md", content)
    puts "  ✅ docs/model_features.md"
  end

  def generate_interactions_doc
    puts "\n🔗 Generating interactions documentation..."

    content = +"# Model Interactions via Concerns\n\n"
    content << "> **Auto-generated** from concern interaction declarations.\n"
    content << "> To regenerate: `rake docs:interactions`\n\n"
    content << "This document describes how models interact with each other through shared concerns.\n\n"
    content << "**Last Updated**: #{Time.current.strftime("%Y-%m-%d %H:%M:%S")}\n\n"
    content << "---\n\n"

    concerns = find_concerns_with_interactions

    concerns.each do |concern|
      content << "## #{concern.name}\n\n"
      content << "This concern enables the following model interactions:\n\n"

      concern.enables_interactions.each do |interaction|
        models = interaction[:models].map { |m| "`#{m}`" }.join(", ")
        content << "### #{interaction[:type].to_s.humanize}\n\n"
        content << "- **Models**: #{models}\n"
        content << "- **Description**: #{interaction[:description]}\n\n" if interaction[:description]
      end

      content << "---\n\n"
    end

    # Model capabilities section
    content << "## Model Capabilities\n\n"

    models_with_concerns = ActiveRecord::Base.descendants.select do |model|
      model.included_modules.any? { |mod| mod.respond_to?(:enables_interactions) }
    end

    models_with_concerns.each do |model|
      content << "### #{model.name}\n\n"
      content << "**Interactions enabled by concerns:**\n\n"

      model.included_modules.select { |mod| mod.respond_to?(:enables_interactions) }.each do |concern|
        concern.enables_interactions.each do |interaction|
          if interaction[:models].include?(model.name.to_sym)
            content << "- **#{interaction[:type].to_s.humanize}**: #{interaction[:description]}\n"
          end
        end
      end

      content << "\n"
    end

    File.write("docs/model_interactions.md", content)
    puts "  ✅ docs/model_interactions.md"
  end

